import { prisma } from '../config/prisma.js';
import { calculateMetadataHash, toBytes32 } from '../utils/hashing.js';
import { BlockchainService } from './blockchainService.js';
import { config } from '../config/index.js';
import { ethers } from 'ethers';

export class CredentialService {
  /**
   * Prepares credential issuance:
   * 1. Creates/finds student
   * 2. Calculates metadata hash
   * 3. Creates PENDING credential in database
   * 4. Returns preparation data for frontend MetaMask signing
   */
  public static async prepareIssuance(data: {
    credentialId: string;
    institutionId: string;
    studentNumber: string;
    studentName: string;
    degreeName: string;
    department: string;
    graduationYear: number;
    grade: string;
    issueDate: Date;
    documentHash: string;
    storageKey: string;
    metadata?: Record<string, any>;
    issuerWallet: string;
  }) {
    // 1. Verify institution exists
    const institution = await prisma.institution.findUnique({
      where: { id: data.institutionId },
    });
    if (!institution) {
      throw new Error('Authorized institution not found.');
    }

    // 2. Find or create student
    let student = await prisma.student.findFirst({
      where: {
        institutionId: data.institutionId,
        studentNumber: data.studentNumber,
      },
    });

    if (!student) {
      // Find or create student user
      const studentEmail = `${data.studentNumber.toLowerCase()}@alumni.iitd.ac.in`;
      let user = await prisma.user.findUnique({ where: { email: studentEmail } });
      if (!user) {
        user = await prisma.user.create({
          data: {
            fullName: data.studentName,
            email: studentEmail,
            passwordHash: 'AUTOGENERATED_STUDENT_HASH',
            role: 'STUDENT',
          },
        });
      }

      student = await prisma.student.create({
        data: {
          userId: user.id,
          institutionId: data.institutionId,
          studentNumber: data.studentNumber,
          fullName: data.studentName,
          normalizedName: data.studentName.toUpperCase().trim(),
          email: studentEmail,
          department: data.department,
        },
      });
    }

    // 3. Calculate deterministic metadata hash
    const canonicalMeta = {
      credentialId: data.credentialId,
      studentNumber: data.studentNumber,
      studentName: data.studentName,
      institutionCode: institution.institutionCode,
      degreeName: data.degreeName,
      graduationYear: data.graduationYear,
      grade: data.grade,
      issueDate: data.issueDate.toISOString().split('T')[0],
      ...(data.metadata || {}),
    };
    const metadataHash = calculateMetadataHash(canonicalMeta);

    // 4. Create PENDING Credential record in DB
    const credential = await prisma.credential.upsert({
      where: { credentialId: data.credentialId },
      update: {
        documentHash: data.documentHash,
        metadataHash,
        documentStorageKey: data.storageKey,
        status: 'PENDING',
        issuerWallet: data.issuerWallet,
      },
      create: {
        credentialId: data.credentialId,
        studentId: student.id,
        institutionId: institution.id,
        degreeName: data.degreeName,
        department: data.department,
        graduationYear: data.graduationYear,
        grade: data.grade,
        issueDate: data.issueDate,
        documentStorageKey: data.storageKey,
        documentHash: data.documentHash,
        metadataHash,
        issuerWallet: data.issuerWallet,
        status: 'PENDING',
      },
    });

    // 5. Convert hashes to bytes32 for contract interaction
    const bytesCredentialId = ethers.keccak256(ethers.toUtf8Bytes(data.credentialId));
    const bytesDocHash = toBytes32(data.documentHash);
    const bytesMetaHash = toBytes32(metadataHash);

    return {
      credential,
      blockchainPreparation: {
        credentialId: data.credentialId,
        bytesCredentialId,
        bytesDocHash,
        bytesMetaHash,
        contractAddress: config.blockchain.registryAddress,
        chainId: config.blockchain.chainId,
      },
    };
  }

  /**
   * Confirms on-chain issuance:
   * 1. Reads transaction receipt on Sepolia
   * 2. Confirms status === 1 and CredentialIssued event match
   * 3. Marks credential ACTIVE in PostgreSQL
   */
  public static async confirmIssuance(credentialId: string, txHash: string) {
    const cred = await prisma.credential.findUnique({ where: { credentialId } });
    if (!cred) throw new Error('Credential not found.');

    const verification = await BlockchainService.verifyIssuanceReceipt(
      txHash,
      credentialId,
      cred.documentHash
    );

    if (!verification.confirmed) {
      throw new Error(`Blockchain verification failed: ${verification.error}`);
    }

    const updated = await prisma.credential.update({
      where: { credentialId },
      data: {
        status: 'ACTIVE',
        blockchainTxHash: txHash,
      },
      include: {
        student: { include: { user: true } },
        institution: true,
      },
    });

    return updated;
  }

  /**
   * Confirms credential revocation:
   */
  public static async confirmRevocation(credentialId: string, txHash: string, reason: string) {
    const cred = await prisma.credential.findUnique({ where: { credentialId } });
    if (!cred) throw new Error('Credential not found.');

    const verification = await BlockchainService.verifyRevocationReceipt(txHash, credentialId);
    if (!verification.confirmed) {
      throw new Error(`Blockchain revocation verification failed: ${verification.error}`);
    }

    const updated = await prisma.credential.update({
      where: { credentialId },
      data: {
        status: 'REVOKED',
        revokedAt: new Date(),
        revocationReason: reason,
        revocationTxHash: txHash,
      },
    });

    return updated;
  }
}

